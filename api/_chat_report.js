'use strict';
const {readFile}=require('node:fs/promises');
const {Document,Packer,Paragraph,TextRun,HeadingLevel}=require('docx');
const {PDFDocument}=require('pdf-lib');
const {screenAnswer}=require('./_chat_privacy');
const MIME='application/vnd.openxmlformats-officedocument.wordprocessingml.document';
const MAX_PAGES=25;
let renderer;
async function referencePages(docx){
  renderer??=Promise.all([
    import('docx-to-pdf-wasm'),
    readFile(require.resolve('docx-to-pdf-wasm/wasm')).then(bytes=>WebAssembly.compile(bytes))
  ]).catch(error=>{renderer=null;throw error;});
  const [{convertToPdf},module]=await renderer;
  const pdf=await convertToPdf(module,new Uint8Array(docx));
  if(pdf.byteLength>8*1024*1024)throw Error('Rendered Chat report size exceeded');
  return (await PDFDocument.load(pdf)).getPageCount();
}
function reportTemplate(answer,compact){
  const children=[new Paragraph({text:'Knowledge Hub Chat report',heading:HeadingLevel.TITLE})];
  const add=text=>children.push(new Paragraph({
    children:[new TextRun({text:screenAnswer(text.replace(/\s+/g,' ')),font:'Arial',size:compact?19:22})],
    spacing:{after:compact?65:150}
  }));
  if(answer.status==='answer'){
    for(const claim of answer.claims)add(claim.text+' ['+claim.refs.join(', ')+']');
    children.push(new Paragraph({text:'Evidence',heading:HeadingLevel.HEADING_1}));
    for(const item of answer.citations){
      const locator=item.page!==null?' · page '+item.page:item.section!==null?' · section '+item.section:'';
      // Labels and citations are generated by the server from the verified evidence references.
      if(!/^(?:Hub source [a-f0-9]{12}|User-provided PDF [12])$/.test(item.label)||
        !/^[AH][1-9][0-9]?$/.test(item.ref))throw Error('Invalid Chat report citation');
      children.push(new Paragraph({text:item.ref+' · '+item.label+locator}));
    }
  }else add(answer.answer);
  if(answer.limited)add('The evidence search or available passages were limited.');
  return new Document({creator:'Knowledge Hub',title:'Knowledge Hub Chat report',
    sections:[{properties:{page:{size:{width:11906,height:16838},
      margin:{top:1134,right:1276,bottom:1134,left:1276}}},children}]});
}
async function createReport(answer,render=referencePages){
  for(const compact of [false,true]){
    const bytes=await Packer.toBuffer(reportTemplate(answer,compact));
    const pages=await render(bytes);
    if(!Number.isSafeInteger(pages)||pages<1)throw Error('Chat report page count invalid');
    if(pages<=MAX_PAGES)return bytes;
  }
  throw Error('Chat report exceeded maximum length');
}
module.exports={createReport,referencePages,MAX_PAGES,MIME};
